// THE ECONOMY PAGE, in the real app: the value table, currencies and keys,
// the reward checker and prize builder, segment conditions, the rounding
// rules, a file out and back in - and the two features that read it (Chef's
// value table, Merge Mania's Syntax tab), and a Merge backup carrying it.
//
//   npx vite-node scripts/e2e/economy-page.mjs   (start `npm run dev` first)
import fs from 'node:fs'
import { BASE, createChecker, launch, openMerge, tab } from './helpers.mjs'

const { ok, finish } = createChecker()
const { browser, page, errors } = await launch({ folded: true })
await page.setViewportSize({ width: 1500, height: 800 })

const text = async (locator) => (await locator.innerText()).replace(/\s+/g, ' ').trim()
const set = async (locator, value) => {
  await locator.fill(String(value))
  await locator.blur()
  await page.waitForTimeout(150)
}
const openEconomy = async () => {
  await page.goto(BASE, { waitUntil: 'networkidle' })
  await page.getByRole('button', { name: /Economy/ }).first().click()
  await page.getByTestId('economy-header').waitFor()
}
const goTab = async (id) => {
  await page.locator(`[data-tab="${id}"]`).click()
  await page.waitForTimeout(150)
}
const noSideScroll = () => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)
page.on('dialog', (d) => d.accept())

console.log('--- 1. The value table ---')
await openEconomy()
ok('the home page offers the Economy page, and it opens on what everything is worth', (await page.locator('[data-economy-tab="worth"]').count()) === 1)
const worthOf = (id) => page.locator(`[data-resource="${id}"] input`).inputValue()
ok(`the economist's table: coins 1, wild 2.5, extra stock 2, undo 0.25, free round 1, and no energy (${[await worthOf('coins'), await worthOf('wild'), await worthOf('stock'), await worthOf('undo'), await worthOf('entry')].join(' ')})`, (await worthOf('coins')) === '1' && (await worthOf('wild')) === '2.5' && (await worthOf('stock')) === '2' && (await worthOf('undo')) === '0.25' && (await worthOf('entry')) === '1' && (await page.locator('[data-resource="energy"]').count()) === 0)
ok('dr-twister is the game\'s name, not marked unverified', (await page.locator('[data-currency="dr-twister"]').count()) === 1 && !/unverified/.test(await text(page.locator('[data-currency="dr-twister"]'))))
ok('dr-hidden and the pack counter are worth 0, the other currencies are not set', (await page.locator('[data-currency="dr-hidden"] input[aria-label$="game play worth"]').inputValue()) === '0' && (await page.locator('[data-currency="dr-pack-counter"] input[aria-label$="game play worth"]').inputValue()) === '0' && (await page.locator('[data-currency="dr-pickaxe"] input[aria-label$="game play worth"]').inputValue()) === '' && (await page.locator('[data-currency="dr-basket-counter"]').count()) === 0 && !/Pricing/i.test(await text(page.getByTestId('economy-currencies').locator('thead'))))
await set(page.locator('[data-resource="wild"] input'), 3)
await page.reload({ waitUntil: 'networkidle' })
await page.getByRole('button', { name: /Economy/ }).first().click()
await page.getByTestId('economy-header').waitFor()
ok('a worth typed is kept in this browser at once (a wild of 3 after a reload)', (await worthOf('wild')) === '3')
await set(page.getByTestId('economy-new-currency'), 'dr_bad')
ok('a currency name that is not dr-kebab-case is refused, and says why', await page.getByTestId('economy-add-currency').isDisabled() && /starts with "dr-"/.test(await text(page.locator('[data-economy-tab="worth"]'))))
await set(page.getByTestId('economy-new-currency'), 'dr-test-gem')
await page.getByTestId('economy-add-currency').click()
await set(page.locator('[data-currency="dr-test-gem"] input[aria-label$="game play worth"]'), 0.2)
ok('the currencies table has no Feature column', !/Feature/i.test(await text(page.getByTestId('economy-currencies').locator('thead'))))
await set(page.locator('[data-currency="dr-test-gem"] input[aria-label$="game play worth"]'), -1)
ok(`a worth below 0 is refused, and it says why ("${(await page.locator('[data-currency="dr-test-gem"] [data-field-rejected-why]').count()) ? await text(page.locator('[data-currency="dr-test-gem"] [data-field-rejected-why]')) : ''}"), the value before kept`, /At least 0/.test(await text(page.locator('[data-currency="dr-test-gem"]'))) && (await page.locator('[data-currency="dr-test-gem"] input[aria-label$="game play worth"]').inputValue()) === '0.2')
await page.getByTestId('economy-daily-toggle-dr-puzzle').click()
await page.locator('[data-daily-editor="dr-puzzle"] summary').click()
await set(page.getByTestId('economy-daily-paste-dr-puzzle'), '2026-02-30=1|nonsense')
await page.getByTestId('economy-daily-use-dr-puzzle').click()
ok(`a list with no real date in it is refused, and it says why (${await text(page.getByTestId('economy-daily-message-dr-puzzle'))})`, /Nothing could be read/.test(await text(page.getByTestId('economy-daily-message-dr-puzzle'))) && /none/.test(await text(page.locator('[data-currency="dr-puzzle"] [data-cell="daily"]'))))
await set(page.getByTestId('economy-daily-paste-dr-puzzle'), '2026-11-30=0.0376875|2026-12-01=0.0333518|2026-12-02=0.0295148')
await page.getByTestId('economy-daily-use-dr-puzzle').click()
ok(`a whole list pasted from a sheet is read (${await text(page.getByTestId('economy-daily-message-dr-puzzle'))})`, /3 dates taken/.test(await text(page.getByTestId('economy-daily-message-dr-puzzle'))) && (await page.locator('[data-daily-editor="dr-puzzle"] [data-daily-row]').count()) === 3)
ok('a new day is picked on a calendar, and starts on the day after the last', (await page.getByTestId('economy-daily-date-dr-puzzle').getAttribute('type')) === 'date' && (await page.getByTestId('economy-daily-date-dr-puzzle').inputValue()) === '2026-12-03')
await set(page.getByTestId('economy-daily-value-dr-puzzle'), 0.0261)
await page.getByTestId('economy-daily-add-dr-puzzle').click()
await page.waitForTimeout(150)
await page.getByTestId('economy-daily-date-dr-puzzle').fill('2026-12-01')
await set(page.getByTestId('economy-daily-value-dr-puzzle'), 0.5)
await page.getByTestId('economy-daily-add-dr-puzzle').click()
await page.waitForTimeout(150)
ok(`a day added; a date that has a value already is refused (${await text(page.getByTestId('economy-daily-message-dr-puzzle'))})`, (await page.locator('[data-daily-editor="dr-puzzle"] [data-daily-row]').count()) === 4 && /has a value already/.test(await text(page.getByTestId('economy-daily-message-dr-puzzle'))))
ok('a currency is added, and its dates are listed (4 dates, 30 Nov to 3 Dec)', (await page.locator('[data-currency="dr-test-gem"]').count()) === 1 && /4 dates, 30 Nov 2026 to 3 Dec 2026/.test(await text(page.locator('[data-currency="dr-puzzle"]'))))
await page.getByTestId('economy-daily-toggle-dr-puzzle').click()
ok('no side scroll on the Worth tab', await noSideScroll())

console.log('--- 2. Keys ---')
await goTab('keys')
ok(`the game's 608 packs are listed, searched rather than scrolled (${await text(page.getByTestId('economy-count-packs'))})`, /^608 keys, the first 12 shown$/.test(await text(page.getByTestId('economy-count-packs'))) && (await page.locator('[data-key-list="packs"] [data-key]').count()) === 12)
await set(page.getByTestId('economy-find-packs'), 'royal_quest')
ok(`typing part of a key finds it, whatever the case (${await text(page.getByTestId('economy-count-packs'))}), every pack worth 0`, /^1 of 608 match$/.test(await text(page.getByTestId('economy-count-packs'))) && (await page.locator('[data-key-list="packs"] [data-key="Royal_T1_1_1R_Vague_Royal_Quest_GP"] input[aria-label$="Worth"]').inputValue()) === '0')
await set(page.getByTestId('economy-paste-packs'), 'sticker_pack:Common_T9_Test_Game\t1.5')
await page.getByTestId('economy-add-packs').click()
await set(page.getByTestId('economy-find-packs'), 'T9_Test')
ok('a pack pasted with its worth is listed (its "sticker_pack:" taken off)', (await page.locator('[data-key="Common_T9_Test_Game"] input[aria-label$="Worth"]').inputValue()) === '1.5')
await set(page.getByTestId('economy-find-presets'), 'Chef_Dish12')
ok('the presets of the third list are there (Chef_Dish12_Complete)', (await page.locator('[data-key-list="presets"] [data-key="Chef_Dish12_Complete"]').count()) === 1)
ok('no side scroll on the Keys tab', await noSideScroll())

console.log('--- 3. Check a reward ---')
await goTab('check')
await page.getByTestId('economy-example-1').click()
await page.waitForTimeout(150)
ok(`the economist's first example reads with nothing to fix (${await text(page.getByTestId('economy-check-verdict'))})`, (await page.locator('[data-check-result="0"]').getAttribute('data-ok')) === 'yes' && (await page.getByTestId('economy-findings').count()) === 0)
ok(`...and with no date chosen the puzzle reads its first date: 0.8 + 0.25 + 5 x 0.0376875 + the pack 0 + a Basic basket 0.25 (${await text(page.getByTestId('economy-worth-total'))})`, (await text(page.getByTestId('economy-worth-total'))) === '1.488438')
await set(page.getByTestId('economy-check-date'), '2026-12-01')
ok(`with 1 Dec chosen: 0.8 + 0.25 + 5 x 0.0333518 + 0 + 0.25 = 1.466759 (${await text(page.getByTestId('economy-worth-total'))})`, (await text(page.getByTestId('economy-worth-total'))) === '1.466759')
await set(page.getByTestId('economy-check-input'), 'allowance(coins:3)+free_wild:1.5+\n[dynamic(dr-made-up:5)]')
const verdicts = await page.getByTestId('economy-check-verdict').allInnerTexts()
ok(`several lines are checked one by one: a broken one, and one readable with a key not on the list (${verdicts.join(' / ')})`, verdicts.length === 2 && /cannot read/.test(verdicts[0]) && /Readable, 1 thing/.test(verdicts[1]))
ok('...the broken one says what is wrong in words', /whole number/.test(await text(page.locator('[data-check-result="0"]'))) && /nothing after it/.test(await text(page.locator('[data-check-result="0"]'))))
await set(page.getByTestId('economy-check-input'), 'allowance(coins:0.125)')
const tierVerdict = await text(page.getByTestId('economy-check-verdict'))
await page.getByTestId('economy-check-where').selectOption('small')
await page.waitForTimeout(150)
ok(`3 decimals of coins are named on a tier prize and allowed on a Merge Mania small reward (${tierVerdict} / ${await text(page.getByTestId('economy-check-verdict'))})`, /1 thing/.test(tierVerdict) && /every key is on the lists/.test(await text(page.getByTestId('economy-check-verdict'))))
ok('no side scroll on the Check tab', await noSideScroll())

console.log('--- 4. Build a prize ---')
await goTab('build')
ok('nothing built yet, and it says so', /Nothing yet/.test(await text(page.getByTestId('economy-build-output'))))
await set(page.getByLabel('Coins', { exact: true }), 3)
await set(page.getByLabel('Wilds', { exact: true }), 1)
ok(`coins and a wild: the text and its worth with a wild of 3 (${await text(page.getByTestId('economy-build-text'))}, ${await text(page.getByTestId('economy-worth-total'))})`, (await text(page.getByTestId('economy-build-text'))) === 'allowance(coins:3)+free_wild:1' && (await text(page.getByTestId('economy-worth-total'))) === '6')
await page.getByTestId('economy-build-pack').selectOption('Common_T4_1_1C_Low_Vague_Game')
await set(page.getByLabel('Pack fallback worth'), 0.5)
const basketKeys = await page.getByTestId('economy-build-basket').locator('option').allInnerTexts()
ok(`the Chef baskets offered are the game-play ones of the list (${basketKeys.length - 1})`, basketKeys.length - 1 === 17 && !basketKeys.some((k) => /pricing/.test(k)) && basketKeys.includes('Chef__Epic_Phase_1_Free_round3'))
await page.getByTestId('economy-build-basket').selectOption('Chef__Rare_Phase_1_Allowance')
await page.getByTestId('economy-build-add-currency').click()
await page.getByLabel('Currency 1', { exact: true }).selectOption('dr-test-gem')
await set(page.getByLabel('Currency 1 amount'), 10)
await page.waitForTimeout(150)
const built = await text(page.getByTestId('economy-build-text'))
ok(`a pack (falling back to 0.5 coins), a Rare basket and a currency (10 x 0.2, falling back to 2 coins), in the standard order (${built})`, built === 'allowance(coins:3)+free_wild:1+preset:Chef__Rare_Phase_1_Allowance+[sticker_pack:Common_T4_1_1C_Low_Vague_Game|allowance(coins:0.5)]+[dynamic(dr-pack-counter:1)|[dynamic(dr-hidden:1)]]+[dynamic(dr-test-gem:10)|allowance(coins:2)]')
ok(`...checked with nothing to fix, worth 3 + 3 + 1 (Rare) + the pack 0 + 2 = 9 (${await text(page.getByTestId('economy-worth-total'))})`, (await page.locator('[data-testid="economy-build-output"] [data-testid="economy-findings"]').count()) === 0 && (await text(page.getByTestId('economy-worth-total'))) === '9')
await page.getByTestId('economy-build-chest').fill('my-new-chest')
await page.waitForTimeout(200)
const chested = await text(page.getByTestId('economy-build-text'))
ok(`a chest name typed wraps the whole prize, and nothing is named for it (${chested.slice(0, 60)}...)`, chested === `chest:my-new-chest(${built})` && (await page.locator('[data-testid="economy-build-output"] [data-testid="economy-findings"]').count()) === 0 && (await text(page.getByTestId('economy-worth-total'))) === '9')
await page.getByTestId('economy-build-chest').fill('')
ok('no side scroll on the Build tab', await noSideScroll())

console.log('--- 5. Segments ---')
await goTab('segments')
ok(`the band ends give one segment a band (${await page.locator('[data-segment]').count()})`, (await page.locator('[data-segment]').count()) === 8)
const BW = '(fn_DailyBrutWins_m4(3,1m,2m,4m,8m)*0.7m+fn_DailyBrutWins_m4(14,1m,2m,4m,8m)*0.3m)'
const MODE = '(fn_DailyAvgModeMultiplier_m4(3,1m,2m,4m,8m)*0.7m+fn_DailyAvgModeMultiplier_m4(14,1m,2m,4m,8m)*0.3m)'
await page.getByTestId('economy-seg-split').check()
await page.waitForTimeout(150)
ok(`split by mode: two a band (${await page.locator('[data-segment]').count()})`, (await page.locator('[data-segment]').count()) === 16)
ok('the economist\'s example, to the character: Disco_BW_9_18_Mode_0_3', (await text(page.locator('[data-segment="Disco_BW_9_18_Mode_0_3"] td').nth(2))) === `${BW} > 9 && ${BW} <= 18 && (${MODE} < 3m)`)
ok('its key is def_ and the name, and the last band is Plus', (await text(page.locator('[data-segment="Disco_BW_9_18_Mode_0_3"] td').nth(1))) === 'def_Disco_BW_9_18_Mode_0_3' && (await page.locator('[data-segment="Disco_BW_240_Plus_Mode_3_plus"]').count()) === 1)
ok('no side scroll on the Segments tab (a condition wraps in its cell)', await noSideScroll())

console.log('--- 6. Rounding ---')
await goTab('rules')
await set(page.getByTestId('economy-rules-x'), 147)
const result = (id) => text(page.locator(`[data-rule="${id}"] [data-cell="result"]`))
ok(`147: RoundReward 140, MergeRoundReward 145, a cost 150 (${await result('roundReward')}, ${await result('mergeRoundReward')}, ${await result('roundCost')})`, (await result('roundReward')) === '140' && (await result('mergeRoundReward')) === '145' && (await result('roundCost')) === '150')
ok('no side scroll on the Rounding tab', await noSideScroll())

console.log('--- 7. A file out, and back in ---')
const [download] = await Promise.all([page.waitForEvent('download'), page.getByTestId('economy-download').click()])
const file = await download.path()
const saved = JSON.parse(fs.readFileSync(file, 'utf8'))
ok('the file holds the economy as typed (a wild of 3, dr-test-gem at 0.2)', saved.kind === 'economy' && saved.economy.resources.wild === 3 && saved.economy.currencies.some((c) => c.name === 'dr-test-gem' && c.valueGameplay === 0.2))
await page.getByTestId('economy-reset').click()
await page.waitForTimeout(200)
await goTab('worth')
ok('"Start again" brings back the economist\'s table (a wild of 2.5, no dr-test-gem)', (await worthOf('wild')) === '2.5' && (await page.locator('[data-currency="dr-test-gem"]').count()) === 0)
await page.getByTestId('economy-load-input').setInputFiles(file)
await page.waitForTimeout(300)
ok('loading the file puts it back, and says so', (await worthOf('wild')) === '3' && (await page.locator('[data-currency="dr-test-gem"]').count()) === 1 && /Loaded from/.test(await text(page.getByTestId('economy-status'))))

console.log('--- 8. Chef reads the value table ---')
await page.goto(BASE, { waitUntil: 'networkidle' })
await page.getByRole('button', { name: /Chef/ }).first().click()
await page.getByTestId('chef-header').waitFor()
await page.locator('[data-chef-step="dishes"]').click()
await page.waitForTimeout(250)
const prizes = page.locator('[data-collapsible="chef-prizes"]')
if (!(await prizes.evaluate((el) => el.open))) await prizes.locator(':scope > summary').click()
ok(`a chef made before says its wild differs from the Economy page's (${await text(page.getByTestId('chef-economy-values'))})`, (await page.getByTestId('chef-economy-values').getAttribute('data-state')) === 'differ' && /Wild 2\.5 here, 3 there/i.test(await text(page.getByTestId('chef-economy-values'))))
await page.getByTestId('chef-use-economy-values').click()
await page.waitForTimeout(200)
ok('one click takes the Economy page\'s, and it then says they are the same', (await page.getByTestId('chef-economy-values').getAttribute('data-state')) === 'same' && (await page.getByLabel('Worth of one Wild', { exact: false }).first().inputValue()) === '3')

console.log('--- 9. Merge Mania\'s Syntax tab reads the item text ---')
await openEconomy()
await page.locator('[data-currency="dr-mf-charm"] button[aria-label^="Remove"]').click()
await page.waitForTimeout(150)
await openMerge(page)
await tab(page, 'Syntax').click()
await page.waitForTimeout(300)
const panel = page.getByTestId('syntax-economy-check')
ok(`with dr-mf-charm off the list, the charm texts are named - readable, a key to look at (${(await panel.count()) ? await text(panel.locator('summary')) : 'no panel'})`, (await panel.count()) === 1 && /readable/.test(await text(panel.locator('summary'))) && (await panel.locator('[data-economy-item^="charms-"]').count()) >= 1)
const [backup] = await Promise.all([page.waitForEvent('download', { timeout: 20000 }), tab(page, 'Export backup').click()]).catch(() => [null])
const backupData = backup ? JSON.parse(fs.readFileSync(await backup.path(), 'utf8')) : null
ok('a Merge Mania backup carries the economy', !!backupData?.economy && backupData.economy.resources.wild === 3)

ok(`no page error (${errors.join(' | ').slice(0, 200)})`, errors.length === 0)
await browser.close()
process.exit(finish('THE ECONOMY PAGE') ? 1 : 0)
