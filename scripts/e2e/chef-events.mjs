// Chef special-event suggestions in the browser (step 4, third choice), on the
// synthetic example (made up). Run: npx vite-node scripts/e2e/chef-events.mjs
import { BASE, createChecker, launch } from './helpers.mjs'

const { ok, finish } = createChecker()
const { browser, page, errors } = await launch({ folded: true })
await page.setViewportSize({ width: 1500, height: 800 })
page.on('dialog', (d) => d.accept())
const text = async (locator) => (await locator.innerText()).replace(/\s+/g, ' ').trim()
const step = async (id) => {
  await page.locator(`[data-chef-step="${id}"]`).click()
  await page.waitForTimeout(250)
}
await page.goto(BASE, { waitUntil: 'networkidle' })
await page.getByRole('button', { name: /Chef/ }).first().click()
await page.getByTestId('chef-header').waitFor()
await page.getByTestId('chef-more').click()
await page.getByTestId('chef-more-panel').getByRole('menuitem', { name: 'New chef: a synthetic example (made up)' }).click()
await page.waitForTimeout(400)
await step('proposal')
await page.getByTestId('chef-step4-kind').locator('[data-option="events"]').click()
await page.waitForTimeout(250)
const rules = await text(page.getByTestId('chef-events-rules'))
ok('step 4 offers special events, and says the economist\'s rules: a share found, common/rare/semi-blocker, never the blocker, the fewest given, one event for all', /share of the players that the search finds/.test(rules) && /Common, rare or the semi-blocker - never the blocker/.test(rules) && /fewer ingredients/.test(rules) && /for every segment alike/.test(rules) && /this tool's own defaults/.test(rules))
ok('nothing missing on the synthetic example', (await page.getByTestId('chef-events-problems').count()) === 0)
await page.getByTestId('chef-events-generate').click()
await page.getByTestId('chef-events-result').waitFor({ timeout: 600000 })
const status = await page.getByTestId('chef-events-result').getAttribute('data-status')
console.log(`      status: ${status}`)
for (const e of await page.locator('[data-event]').allInnerTexts()) console.log(`      ${e.replace(/\s+/g, ' ').slice(0, 200)}`)
ok(`a suggestion comes back with its status (${status})`, ['meets', 'misses', 'no-better', 'already'].includes(status))
if (status === 'meets' || status === 'misses') {
  const events = await page.locator('[data-event]').allInnerTexts()
  ok(`each event is said in words: day, amount, ingredient, share of every segment (${events.length})`, events.length >= 1 && events.every((e) => /a special event gives \d+ .* to \d+% of the players of every segment/.test(e)))
  ok('a row a segment, the targets now → with it and their verdict, and what a player was given', (await page.locator('[data-events-segment]').count()) >= 1 && /→/.test(await text(page.locator('[data-events-segment]').first().locator('[data-cell="target-fu"]'))) && /\d/.test(await text(page.locator('[data-events-segment] [data-cell="given"]').first())))
  const why = page.locator('[data-collapsible="chef-events-why"]')
  ok(`what holds players back on the FU day is read, and says the semi-blocker is held by its threshold (${await text(why.locator(':scope > summary'))})`, (await why.count()) === 1 && (await why.evaluate((el) => el.open)) && /never past its threshold/.test(await text(page.getByTestId('chef-events-why'))) && /Pumpkin \(semi-blocker\)/.test(await text(page.getByTestId('chef-events-why'))))
  await page.getByTestId('chef-events-apply').click()
  await page.waitForTimeout(300)
  ok('applied: in use, with an undo', (await page.getByTestId('chef-events-in-use').count()) === 1 && (await page.getByTestId('chef-events-undo').count()) === 1)
  await step('baskets')
  const grants = page.locator('[data-collapsible="chef-grants"]')
  if (!(await grants.evaluate((el) => el.open))) await grants.locator(':scope > summary').click()
  await page.waitForTimeout(200)
  ok(`step 3 lists the suggested events, marked "Suggested (step 4)" (${await page.locator('[data-source-suggested]').count()})`, (await page.locator('[data-source-suggested]').count()) === events.length)
  await step('proposal')
  await page.getByTestId('chef-events-undo').click()
  await page.waitForTimeout(300)
  await step('baskets')
  ok('one undo takes them out again', (await page.locator('[data-source-suggested]').count()) === 0)
}
ok('no side scroll', await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1))
ok(`no page error (${errors.join(' | ').slice(0, 200)})`, errors.length === 0)
await browser.close()
process.exit(finish('CHEF SPECIAL EVENTS') ? 1 : 0)
