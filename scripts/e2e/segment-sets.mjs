// Segment sets: the flow saved as a set on the Economy page, every set's efforts edited in one place, a set picked in
// Merge's step 1 (copied with its efforts), the set changed afterwards and its new numbers taken.
// Run: npx vite-node scripts/e2e/segment-sets.mjs
import { BASE, createChecker, launch, tab } from './helpers.mjs'

const { ok, finish } = createChecker()
const { browser, page, errors } = await launch()
page.on('dialog', (d) => d.accept())
const set = async (locator, value) => {
  await locator.fill(String(value))
  await locator.blur()
  await page.waitForTimeout(250)
}
const openEconomySegments = async () => {
  await page.goto(BASE, { waitUntil: 'networkidle' })
  await page.getByRole('link', { name: /Economy/ }).first().click()
  await page.getByTestId('economy-header').waitFor()
  await page.locator('[data-tab="segments"]').click()
  await page.waitForTimeout(300)
}
const view = async (id) => {
  await page.locator(`[data-seg-view="${id}"]`).click()
  await page.waitForTimeout(250)
}

// The Economy page: a set from the flow.
await openEconomySegments()
await view('sets')
ok('the Segments tab has the segment sets, none yet', (await page.getByTestId('economy-segment-sets').count()) === 1 && (await page.getByTestId('economy-sets-empty').count()) === 1)
await view('build')
ok('"Save as a set" sits on the segments the flow makes', (await page.getByTestId('economy-seg-table').count()) === 1 && (await page.getByTestId('economy-set-save').count()) === 1)
await set(page.getByTestId('economy-seg-feature'), '2D_Levels')
await set(page.getByTestId('economy-seg-cuts'), '1000, 2500')
await page.getByTestId('economy-set-name').fill('Level features, 2 days')
await page.getByTestId('economy-set-save').click()
await page.waitForTimeout(300)
const savedMessage = await page.getByTestId('economy-set-message').innerText()
await view('sets')
const sets = page.getByTestId('economy-segment-sets')
ok(`the flow is saved as a set (${savedMessage})`, (await sets.locator('[data-set]').count()) === 1 && (await sets.locator('[data-set-segment]').count()) === 3)
ok(`the feature typed is the set's name placeholder, shown in its segments' names (${(await sets.locator('[data-set-segment="BW_0_1000"] td').first().innerText()).trim()})`, (await sets.locator('[data-set-segment="BW_0_1000"]').count()) === 1 && (await sets.locator('[data-set]').first().getAttribute('data-set') ) && (await sets.locator('[data-set-placeholder="2D_Levels"]').count()) === 1 && /^2D_Levels_BW_0_1000$/.test((await sets.locator('[data-set-segment="BW_0_1000"] td').first().innerText()).trim()))
await view('build')
await page.getByTestId('economy-set-name').fill('Weekend features')
await page.getByTestId('economy-set-save').click()
await page.waitForTimeout(300)
await view('sets')
ok('a second set, side by side with the first; the Sets view counts them', (await sets.locator('[data-set]').count()) === 2 && /2/.test(await page.locator('[data-seg-view="sets"]').innerText()))
// Every set's efforts in one place.
const effort = (setIndex, id) => sets.locator('[data-set]').nth(setIndex).locator(`[data-set-segment="${id}"] [data-set-effort]`)
await set(effort(0, 'BW_0_1000'), 40)
await set(effort(0, 'BW_1000_2500'), 90)
await set(effort(1, 'BW_0_1000'), 25)
ok('efforts of both sets are typed on the same card', (await effort(0, 'BW_0_1000').inputValue()) === '40' && (await effort(1, 'BW_0_1000').inputValue()) === '25')
await page.reload({ waitUntil: 'networkidle' })
await page.locator('[data-tab="segments"]').click().catch(() => {})
await page.waitForTimeout(300)
ok('the view open is remembered (Segment sets)', (await page.locator('[data-seg-view="sets"]').getAttribute('aria-selected')) === 'true')
ok('the sets and their efforts are kept after a reload', (await effort(0, 'BW_1000_2500').inputValue()) === '90')

// Generic segments: no feature typed, the set's name stands in for it.
await view('build')
await set(page.getByTestId('economy-seg-feature'), '')
const firstName = () => page.locator('[data-testid="economy-seg-table"] tbody tr td').first().innerText()
ok(`no feature typed: nothing to fix, the segments are generic (${(await firstName()).trim()})`, (await page.locator('[data-plan-error]').count()) === 0 && (await page.getByTestId('economy-seg-generic').count()) === 1 && /^Feature_BW_0_1000$/.test((await firstName()).trim()))
await page.getByTestId('economy-set-name').fill('2D_Levels')
await page.waitForTimeout(250)
ok(`the set's name names them as it is typed (${(await firstName()).trim()})`, /^2D_Levels_BW_0_1000$/.test((await firstName()).trim()) && /2D_Levels_/.test(await page.getByTestId('economy-seg-generic').innerText()))
await page.getByTestId('economy-set-save').click()
await page.waitForTimeout(300)
await view('sets')
ok('saved as a generic set, 2D_Levels its placeholder', (await sets.locator('[data-set]').count()) === 3 && (await sets.locator('[data-set]').nth(2).locator('[data-set-placeholder="2D_Levels"]').count()) === 1)

// Merge: the set picked.
await page.goto(BASE, { waitUntil: 'networkidle' })
await page.getByText('Merge Mania', { exact: false }).first().click()
await page.waitForTimeout(300)
await tab(page, 'Build event').click()
await page.waitForTimeout(400)
const picker = page.getByTestId('merge-segment-set')
const options = await picker.locator('option').allInnerTexts()
ok(`step 1 offers the sets in a list (${options.join(' / ')})`, options.some((o) => /Level features, 2 days - 3 segments/.test(o)) && options.some((o) => /Weekend features/.test(o)))
const levelId = await picker.locator('option', { hasText: 'Level features' }).getAttribute('value')
await picker.selectOption(levelId)
await page.waitForTimeout(500)
ok(`picking it copies the segments (${await page.getByTestId('merge-segments-message').innerText()})`, /3 segments taken from "Level features, 2 days", named Merge_ in place of 2D_Levels_, 2 with an effort/.test(await page.getByTestId('merge-segments-message').innerText()))
const rows = await page.locator('[data-testid="setup-segments"] [data-setup-segment]').evaluateAll((trs) =>
  trs.map((tr) => ({ name: tr.querySelector('button')?.innerText.trim(), effort: tr.querySelector('[data-field="effort-bw"]')?.value, condition: tr.querySelector('[data-field="condition"]')?.innerText })),
)
console.log(`      ${rows.map((r) => `${r.name}=${r.effort}`).join(' | ')}`)
ok('Merge\'s names, conditions and the efforts in Brut Wins', rows.length === 3 && rows[0].name === 'Merge_BW_0_1000' && rows[0].effort === '40' && rows[1].effort === '90' && rows[2].effort === '' && rows.every((r) => !!r.condition))
ok('the flow below holds the set\'s flow, with Merge\'s name', (await page.getByTestId('economy-seg-feature').inputValue()) === 'Merge' && (await page.getByTestId('economy-seg-cuts').inputValue()) === '1000, 2500')
ok('nothing says the set changed', (await page.getByTestId('merge-set-changed').count()) === 0)
ok('Merge\'s own flow still asks for its feature (it is never generic)', (await page.getByTestId('economy-seg-generic').count()) === 0)
await page.locator('header').getByRole('button', { name: 'Save', exact: true }).click()
await page.waitForTimeout(300)

// The set changed on the Economy page: the event keeps its copy until told.
await openEconomySegments()
await view('sets')
await set(effort(0, 'BW_0_1000'), 55)
await page.goto(BASE, { waitUntil: 'networkidle' })
await page.getByText('Merge Mania', { exact: false }).first().click()
await page.waitForTimeout(300)
await tab(page, 'Build event').click()
await page.waitForTimeout(400)
const first = () => page.locator('[data-setup-segment="0"] [data-field="effort-bw"]').inputValue()
ok('the event keeps its copy (40) and says the set changed since', (await first()) === '40' && (await page.getByTestId('merge-set-changed').count()) === 1)
await page.getByTestId('merge-set-retake').click()
await page.waitForTimeout(400)
ok('"Take its new numbers" brings 55 in, and the notice goes', (await first()) === '55' && (await page.getByTestId('merge-set-changed').count()) === 0)
await picker.selectOption(await picker.locator('option', { hasText: '2D_Levels' }).getAttribute('value'))
await page.waitForTimeout(500)
ok(`the generic set taken by Merge: Merge_ in place of 2D_Levels_ (${await page.getByTestId('merge-segments-message').innerText()})`, /in place of 2D_Levels_/.test(await page.getByTestId('merge-segments-message').innerText()) && (await page.locator('[data-setup-segment="0"] button').first().innerText()).trim() === 'Merge_BW_0_1000')
// A set with mode splits: one factor between the modes, for all of them at once.
await openEconomySegments()
await view('build')
await set(page.getByTestId('economy-seg-feature'), '')
await set(page.getByTestId('economy-seg-cuts'), '9')
await page.getByTestId('economy-split-add').click()
await page.waitForTimeout(200)
await set(page.getByTestId('economy-split-values-0'), '3')
await page.getByTestId('economy-split-segments-0').locator('[data-pick="all"]').click()
await page.waitForTimeout(300)
await page.getByTestId('economy-set-name').fill('Modes')
await page.getByTestId('economy-set-save').click()
await page.waitForTimeout(300)
await view('sets')
const modesCard = sets.locator('[data-set]', { has: page.locator('[data-set-name]') }).filter({ has: page.locator('[data-set-segment="BW_0_9_Mode_3_plus"]') })
ok(`the set with mode splits offers one factor for all of them (${(await modesCard.locator('[data-set-mode-factor]').innerText().catch(() => 'none')).replace(/\s+/g, ' ')})`, (await modesCard.locator('[data-set-mode-factor]').count()) === 1)
await set(modesCard.locator('[data-set-segment="BW_0_9_Mode_0_3"] [data-set-effort]'), 40)
await set(modesCard.locator('[data-set-segment="BW_9_Plus_Mode_0_3"] [data-set-effort]'), 100)
await modesCard.locator('[data-set-mode-factor-input]').fill('1.5')
await modesCard.locator('[data-set-mode-factor-apply]').click()
await page.waitForTimeout(300)
const followed = (id) => modesCard.locator(`[data-set-segment="${id}"] [data-set-effort-value]`).innerText()
ok(`each higher mode = the lower x 1.5 (${await followed('BW_0_9_Mode_3_plus')}, ${await followed('BW_9_Plus_Mode_3_plus')})`, (await followed('BW_0_9_Mode_3_plus')) === '= 60' && (await followed('BW_9_Plus_Mode_3_plus')) === '= 150')
await set(modesCard.locator('[data-set-segment="BW_0_9_Mode_0_3"] [data-set-effort]'), 50)
ok('the higher mode follows the lower: 50 x 1.5 = 75', (await followed('BW_0_9_Mode_3_plus')) === '= 75')
await page.goto(BASE, { waitUntil: 'networkidle' })
await page.getByText('Merge Mania', { exact: false }).first().click()
await page.waitForTimeout(300)
await tab(page, 'Build event').click()
await page.waitForTimeout(400)
await picker.selectOption(await picker.locator('option', { hasText: 'Modes' }).getAttribute('value'))
await page.waitForTimeout(500)
const mergeEfforts = await page.locator('[data-testid="setup-segments"] [data-setup-segment] [data-field="effort-bw"]').evaluateAll((els) => els.map((e) => e.value))
ok(`Merge takes the efforts worked out (${mergeEfforts.join(', ')})`, mergeEfforts.join(',') === '50,75,100,150')
ok(`no page error (${errors.join(' | ').slice(0, 200)})`, errors.length === 0)
await browser.close()
process.exit(finish('SEGMENT SETS') ? 1 : 0)
