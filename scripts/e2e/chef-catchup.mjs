// CHEF BUILD 03 IN THE BROWSER: step 4's catch-up suggestions on the synthetic
// example (made up) - the choice in step 4, the rules said, a suggestion made
// and checked, applied (marked in step 3), undone, and out of date after an
// edit. Run: npx vite-node scripts/e2e/chef-catchup.mjs (start `npm run dev`).
import { BASE, createChecker, launch } from './helpers.mjs'

const { ok, finish } = createChecker()
const { browser, page, errors } = await launch({ folded: true })
await page.setViewportSize({ width: 1500, height: 800 })
page.on('dialog', (d) => d.accept())
const text = async (locator) => (await locator.innerText()).replace(/\s+/g, ' ').trim()
const step = async (id) => {
  await page.locator(`[data-chef-step="${id}"]`).click()
  await page.waitForTimeout(250)
}

await page.goto(BASE, { waitUntil: 'networkidle' })
await page.getByRole('button', { name: /Chef/ }).first().click()
await page.getByTestId('chef-header').waitFor()
await page.getByTestId('chef-more').click()
await page.getByTestId('chef-more-panel').getByRole('menuitem', { name: 'New chef: a synthetic example (made up)' }).click()
await page.waitForTimeout(400)
await step('proposal')

console.log('--- 1. The choice in step 4, and the rules said ---')
ok('step 4 offers two kinds of suggestion, the proposal first', /Recipes, weights and thresholds/.test(await text(page.getByTestId('chef-step4-kind'))) && (await page.getByTestId('chef-step4-kind').locator('[data-option="proposal"]').getAttribute('aria-pressed')) === 'true')
await page.getByTestId('chef-step4-kind').locator('[data-option="catchup"]').click()
await page.waitForTimeout(250)
const rules = await text(page.getByTestId('chef-catchup-rules'))
ok('the economist\'s rules are said: both kinds of player, common and rare only, their presets untouched, fewest players', /behind pace/.test(rules) && /stuck on an ingredient/.test(rules) && /only common and rare ingredients/.test(rules) && /never the semi-blocker or the blocker/.test(rules) && /nothing of (it|them) is changed/.test(rules) && /fewer players/.test(rules))
ok('the defaults are said to be this tool\'s own', /this tool's own defaults/.test(rules))
ok('it aims at the same targets as a proposal, in words', /On day 14, 80% of the players of each segment sitting in FU/.test(await text(page.getByTestId('chef-catchup-targets'))))
ok('Epic is off to start with, Basic and Rare on', (await page.getByTestId('chef-catchup-type-epic').isChecked()) === false && (await page.getByTestId('chef-catchup-type-basic').isChecked()) && (await page.getByTestId('chef-catchup-type-rare').isChecked()))
ok('nothing missing on the synthetic example', (await page.getByTestId('chef-catchup-problems').count()) === 0)
await page.getByTestId('chef-catchup-kind-pace').uncheck()
await page.getByTestId('chef-catchup-kind-stuck').uncheck()
await page.waitForTimeout(200)
ok('with neither kind of player allowed, it says what is missing and cannot run', /Neither kind of player/.test(await text(page.getByTestId('chef-catchup-problems'))) && (await page.getByTestId('chef-catchup-generate').isDisabled()))
await page.getByTestId('chef-catchup-kind-pace').check()
await page.getByTestId('chef-catchup-kind-stuck').check()
await page.waitForTimeout(200)

console.log('--- 2. A suggestion ---')
await page.getByTestId('chef-catchup-generate').click()
await page.getByTestId('chef-catchup-result').waitFor({ timeout: 600000 })
const status = await page.getByTestId('chef-catchup-result').getAttribute('data-status')
console.log(`      status: ${status} - ${await text(page.getByTestId('chef-catchup-status'))}`)
ok(`a suggestion comes back with a status in words (${status})`, ['meets', 'misses', 'no-better', 'already'].includes(status))
if (status === 'meets' || status === 'misses') {
  const presets = await page.locator('[data-catchup-preset]').allInnerTexts()
  for (const p of presets) console.log(`      ${p.replace(/\s+/g, ' ').slice(0, 220)}`)
  ok(`each suggested preset is said in words: kind, who, days, the basket, what it holds (${presets.length})`, presets.length >= 1 && presets.every((p) => /(Behind pace|Stuck on an ingredient)/.test(p) && /on days \d+ to \d+/.test(p) && /a basket of \d+:/.test(p)))
  ok('a row a segment: the targets now → with it, with a verdict, the other view, and the players touched', (await page.locator('[data-catchup-segment]').count()) >= 1 && /→/.test(await text(page.locator('[data-catchup-segment]').first().locator('[data-cell="target-fu"]'))) && (await page.getByTestId('chef-catchup-other-head').count()) === 1 && /%/.test(await text(page.locator('[data-catchup-segment] [data-cell="touched"]').first())))
  const why = page.locator('[data-collapsible="chef-catchup-why"]')
  ok(`what holds players back on the FU day is read, and opens by itself when it is the semi-blocker (${await text(why.locator(':scope > summary'))})`, (await why.count()) === 1 && (await why.evaluate((el) => el.open)) && /Pumpkin \(semi-blocker\)/.test(await text(page.getByTestId('chef-catchup-why'))) && !/Green Jelly/.test(await text(page.getByTestId('chef-catchup-why'))))
  const before = await page.evaluate(() => localStorage.length)
  await page.getByTestId('chef-catchup-apply').click()
  await page.waitForTimeout(400)
  ok('applied: in use, and the undo is offered', (await page.getByTestId('chef-catchup-in-use').count()) === 1 && (await page.getByTestId('chef-catchup-undo').count()) === 1 && before >= 0)
  await step('baskets')
  const presetsFold = page.locator('[data-collapsible="chef-presets"]')
  if ((await presetsFold.count()) && !(await presetsFold.evaluate((el) => el.open))) await presetsFold.locator(':scope > summary').click()
  await page.waitForTimeout(200)
  ok(`step 3 lists the suggested presets, marked "Suggested (step 4)" (${await page.locator('[data-preset-suggested]').count()})`, (await page.locator('[data-preset-suggested]').count()) === presets.length)
  await step('proposal')
  await page.getByTestId('chef-catchup-undo').click()
  await page.waitForTimeout(300)
  await step('baskets')
  if ((await presetsFold.count()) && !(await presetsFold.evaluate((el) => el.open))) await presetsFold.locator(':scope > summary').click()
  ok('one undo takes them out of step 3 again', (await page.locator('[data-preset-suggested]').count()) === 0)
  await step('proposal')
  ok('step 4 remembers that the catch-up view was open', (await page.getByTestId('chef-catchup').count()) === 1)
  await step('event')
  const effort = page.locator('[data-segment] input[aria-label*="ffort"]').first()
  if (await effort.count()) {
    await effort.fill('1.37')
    await effort.blur()
    await page.waitForTimeout(200)
    await step('proposal')
    ok('after an edit of the event the suggestion is out of date and cannot be applied', (await page.getByTestId('chef-catchup-stale').count()) === 1 && (await page.getByTestId('chef-catchup-apply').count()) === 0)
  }
}
ok(`no page error (${errors.join(' | ').slice(0, 200)})`, errors.length === 0)
await browser.close()
process.exit(finish('CHEF CATCH-UP') ? 1 : 0)
